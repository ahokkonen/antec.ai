# Каждому сервису свой подкаталог: контейнер монтирует только своё (LiteLLM не видит агентов).
LITELLM_MODELS = "litellm/models.yaml"
AGENTS = "platform-api/agents.json"
MCP_SERVERS = "platform-api/mcp_servers.json"
